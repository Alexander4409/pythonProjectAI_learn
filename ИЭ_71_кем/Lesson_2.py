# пример программы которая разрешает доступ в зависимости от возраста

user_age = int(input("Укажите ваш возраст: "))
print(f"Ваш возраст - {user_age}")
if user_age >= 18:
    print("Доступ разрешен! Добро пожаловать!")
else:
    print("Доступ запрещен!")

