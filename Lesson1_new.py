# Работа со списками
def test_id_funcList() -> None:
    lst_1 = [10]
    lst_2 = lst_1

    print(f'list1:id {id(lst_1)}')
    print(f'list2:id {id(lst_2)}')

    lst_1.append(11)
    print(f'list1:id {id(lst_1)}')
    print(f'list2:id {id(lst_2)}')


test_id_funcList()
