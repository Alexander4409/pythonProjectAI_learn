# Функция проверки id
def test_id_func() -> None:
    num = 10
    num_2 = num

    print(f'num:id {id(num)}')
    print(f'num:id {id(num_2)}')

    num -= 1#Икримент
    print(f'num:id {id(num)}')



test_id_func()

#В случае использования оператора (=) происходит копирование информации
