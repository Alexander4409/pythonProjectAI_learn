# циклы while/for

num = 0
while num <= 100:


    num += 1
    if num == 5:
        continue

    print(f"Число - {num}")

    if num == 10:
        print("Аварийная остановка цикла")
        break



# проверяет истинность утверждения и выполняет инструкцию в
# своём теле до тех пор пока выражение истинно

# break полностью останавливает цикл
